import { TECHNIQUES } from './suggestCore.js'

// Сборка сообщений для DeepSeek. Кандидатам режем описание, чтобы промпт был
// коротким (скорость). Маржу/себестоимость модели не показываем — только «why».
export function buildMessages({ candidates, stage, tag, guest, cart }) {
  const menu = candidates.map(c => ({
    id: c.id,
    name: c.name,
    price: c.price,
    desc: (c.description || '').slice(0, 120),
    why: [
      c.pushReason,
      c.dailyFlag === 'expiring' ? 'последний день реализации' : null,
      c.dailyFlag === 'special' ? 'спец дня от шефа' : null,
    ].filter(Boolean).join('; ') || null,
  }))
  const g = guest || {}
  const guestLine = [
    g.gender && `пол: ${g.gender}`,
    g.age && `возраст: ${g.age}`,
    g.occasion && `повод: ${g.occasion}`,
    g.partySize ? `гостей за столом: ${g.partySize}` : null,
    g.preferences && `предпочтения/ограничения: ${g.preferences}`,
  ].filter(Boolean).join(', ') || 'не указан'

  const system = `Ты — опытный наставник-официант и сомелье. Из списка кандидатов ты САМ ВЫБИРАЕШЬ 1–3 блюда, которые лучше всего ДОПОЛНЯТ уже выбранное гостем, и подсказываешь официанту, что именно сказать. Не пиши фразу к каждому кандидату — выбирай только по-настоящему уместные.

Действуй по шагам:
1) ГОСТЬ. Посмотри, что гость УЖЕ выбрал (см. «Уже в заказе»), его профиль (пол, возраст, повод, число гостей) и предпочтения. Если гость просил что-то исключить (без чеснока, без острого, не любит рыбу и т. п.) — такие блюда НЕ предлагай ни при каких условиях.
2) СОЧЕТАЕМОСТЬ. Отбери из кандидатов только то, что реально СОЧЕТАЕТСЯ с выбранным — по вкусу, сытности, свежести, температуре. Не повторяй и не заменяй уже выбранное. Если в заказе уже есть основное/горячее — предлагай ДОПОЛНЕНИЕ (закуску, салат, суп, гарнир, соус, десерт), а не второе конкурирующее горячее (люди не берут пиццу И стейк). Если гость ещё ничего не выбрал — предложи удачные блюда для начала под его профиль и повод.
3) ВЫГОДА. Если несколько кандидатов сочетаются одинаково хорошо — предпочти те, что ВЫШЕ в списке (он отсортирован по выгоде ресторана: маржа и срок реализации, у части есть пометка why). Но гостю про маржу, себестоимость и выгоду ресторана НИКОГДА не говори.

Соизмеряй с числом гостей и поводом: одному гостю — одиночные порции, не «две пиццы и две колы»; под повод (романтика, деловая, семья, праздник) — уместное.
Выбери столько, сколько реально уместно (1–3, лучшее первым). Если из кандидатов ничего толком не сочетается с выбранным — верни пустой список, не тяни случайное.

Для каждого выбранного блюда pitch — это ГОТОВЫЙ СКРИПТ официанту из двух частей:
1) короткая директива, ЧТО предложить (без кавычек; название блюда — тоже без кавычек);
2) затем ПРЯМАЯ РЕПЛИКА гостю — дословно, с приёмом продаж, в кавычках «…» (ровно ОДНИ внешние кавычки на всю реплику, внутри кавычек больше НЕ ставь; в приложении текст в «…» выделяется жирным, поэтому туда — ТОЛЬКО произносимая фраза).
   Выбери ОДИН, самый уместный приём (в ответе укажи его код в поле technique):
   • вкусовое сочетание (technique="taste_pairing") — «к пицце отлично зайдёт лёгкий салат — освежит и разбавит сытное тесто»;
   • социальное доказательство (technique="social_proof") — «сегодня гости чаще всего берут к этому наш Цезарь»;
   • выбор без выбора (technique="choice_no_choice") — «к стейку принести соус перечный или грибной?»;
   • срочность/дефицит (technique="scarcity") — «осталась последняя порция сегодняшнего салата».
   Реплика — живая и конкретная, с названием блюда; без цен и чисел. Под повод: романтика — камернее, компания/праздник — легче.
- addon — необязательная вторая пара (например, к десерту — кофе) или null.

Верни СТРОГО JSON: {"suggestions":[{"dishId":"<id из списка>","pitch":"<директива + «реплика в кавычках»>","technique":"<код приёма>","addon":"<пара или null>"}]}. Только ВЫБРАННЫЕ блюда, в порядке предпочтения. Бери id ТОЛЬКО из списка кандидатов, не выдумывай.`

  const cartLine = Array.isArray(cart) && cart.length
    ? `\nУже в заказе у гостя: ${cart.join(', ')}.`
    : ''
  const user = `Стадия: ${stage || 'консультация'}. Тег/запрос: ${tag || 'общий совет'}. Гость: ${guestLine}.${cartLine}
Кандидаты (по убыванию приоритета):
${JSON.stringify(menu)}`

  return [
    { role: 'system', content: system },
    { role: 'user', content: user },
  ]
}

// Разбор ответа DeepSeek. Отбрасываем всё, что не из набора кандидатов
// (защита от галлюцинаций id). null → вызвать шаблонный фолбэк.
export function parsePitches(content, candidates) {
  if (!content) return null
  let obj
  try { obj = JSON.parse(content) } catch { return null }
  const arr = Array.isArray(obj) ? obj : (obj.suggestions || obj.items || [])
  if (!Array.isArray(arr)) return null
  const ids = new Set(candidates.map(c => c.id))
  const out = arr
    .filter(x => x && ids.has(x.dishId) && typeof x.pitch === 'string' && x.pitch.trim())
    .map(x => ({
      dishId: x.dishId,
      pitch: x.pitch.trim(),
      technique: TECHNIQUES.has(x.technique) ? x.technique : null,
      addon: x.addon && String(x.addon).trim() && String(x.addon).trim().toLowerCase() !== 'null'
        ? String(x.addon).trim() : null,
    }))
  return out.length ? out : null
}

